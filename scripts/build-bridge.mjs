// Bundle LIVE runtime thành IIFE classic script cho public/integration/runtime.generated.js (gitignore).
// Chạy: npm run build:bridge  (thêm --check để chỉ build vào thư mục tạm và kiểm tra global).
import { build } from "esbuild";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const tmp = check ? mkdtempSync(path.join(tmpdir(), "voicevault-bridge-")) : null;
const outfile = check ? path.join(tmp, "runtime.generated.js") : path.join(root, "public/integration/runtime.generated.js");

await build({
  entryPoints: [path.join(root, "src/integration/bridge-entry.ts")],
  outfile,
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  legalComments: "none",
  banner: { js: "/* GENERATED by scripts/build-bridge.mjs. Do not edit. */" },
  logLevel: "warning",
});

// Smoke: script chạy trong context trống và gán đúng global.
const context = { crypto: globalThis.crypto, TextEncoder, TextDecoder, URLSearchParams, btoa, atob };
context.globalThis = context;
vm.runInNewContext(readFileSync(outfile, "utf8"), context);
if (typeof context.createVoiceVaultLiveRuntime !== "function" || context.VoiceVaultLiveInfo?.contractVersion !== "v1") {
  console.error("bundle không gán window.createVoiceVaultLiveRuntime v1");
  process.exit(1);
}
console.log(`built ${check ? "(check) " : ""}${path.relative(root, outfile) || outfile}`);
if (tmp) rmSync(tmp, { recursive: true, force: true });
